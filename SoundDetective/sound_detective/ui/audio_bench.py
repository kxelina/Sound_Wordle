    def _translate(self):
        from .hover_help import apply_window_help
        text = TEXT[self._language]
        self.setWindowTitle(text["title"])
        self.title.setText(text["title"])
        for name in ("subtitle", "target_info", "play_a", "play_b", "play_ab", "filter", "delay", "reverb", "note"):
            getattr(self, name).setText(text[name])
        self.target_group.setTitle(text["target_group"])
        self.current_group.setTitle(text["current_group"])
        for name in ("source", "preset", "release", "cutoff", "volume"):
            getattr(self, name + "_label").setText(text[name])
        self.stop_button.setText(text["stop"])
        self.compare_button.setText(text["compare"])
        for control in (self.source, self.preset):
            for index in range(control.count()):
                control.setItemText(index, text[control.itemData(index)])
        self._status(self._status_key, **self._status_args)
        self._device()
        self._show_match()

        apply_window_help(self, "bench", self._language)

    def _show_match(self):
        text = TEXT[self._language]
        result = self._match_result
        if result is None:
            self.score.setText(text["unscored"])
            self.clue.clear()
        else:
            self.score.setText(text["result"].format(total=result.total, spectrum=result.spectrum,
                envelope=result.envelope, tail=result.tail, outcome=text["passed" if result.passed else "retry"]))
            self.clue.setText("\n".join(diagnose(result, self._language)[:2]))

    def _change_language(self):
        self._language = self.language.currentData()
        self._translate()

    def _status(self, key, **arguments):
        self._status_key, self._status_args = key, arguments
        args = dict(arguments)
        if "label" in args:
            args["label"] = TEXT[self._language].get(args["label"], args["label"])
        self.status.setText(TEXT[self._language][key].format(**args))

    def _device(self):
        text = TEXT[self._language]
        self.device.setText(text["device"].format(name=self.player.device_name or text["none"]))

    def _volume_changed(self, value):
        self.volume_value.setText(f"{value}%")
        self.player.set_volume(value / 100)

    def _parameters_changed(self, *_):
        if not hasattr(self, "_debounce") or self._closed:
            return
        self.stop()
        self._match_result = None
        self._show_match()
        self._status("updated")
        self._debounce.start()

    def _requests(self, mode):
        source = self.source.currentData()
        if source == "single":
            sequence = NoteSequence((NoteEvent(60, .08, .8, 110),))
        else:
            filename = "three-note-example.json" if source == "three" else "detective-motif.json"
            sequence = NoteSequence.from_dict(json.loads((ROOT / "content/music" / filename).read_text(encoding="utf-8-sig")))
        bright = (1, .5, .33, .25, .2, .17, .14, .125)
        target = SoundSettings(SynthPatch(harmonics=bright, attack=.02, decay=.18, sustain=.6, release=.25))
        preset = self.preset.currentData()
        partials = {"bright": bright, "soft": (1, .2, .08, 0, 0, 0, 0, 0),
                    "hollow": (1, 0, .33, 0, .2, 0, .14, 0)}[preset]
        patch = SynthPatch(harmonics=partials, attack=.3 if preset == "soft" else .02,
                           decay=.18, sustain=.6, release=self.release.value())
        current = SoundSettings(patch, EffectSettings(
            filter=FilterSettings(self.filter.isChecked(), "lowpass", self.cutoff.value(), .25),
            delay=DelaySettings(self.delay.isChecked(), .28, 1.5, .3),
            reverb=ReverbSettings(self.reverb.isChecked(), .5, .5, .25)))
        return {label: (settings, sequence) for label, settings in (("a", target), ("b", current))
                if mode is None or mode in ("ab", "compare") or mode == label}

    def _prepare(self, mode):
        if self._closed:
            return
        self._debounce.stop()
        self.player.stop()
        self._revision = None
        self._match_revision = None
        self.renderer.cancel()
        self._armed = mode
        self.busy.show()
        self._status("preparing")
        try:
            if mode == "compare":
                self._match_result = None
                self._show_match()
                self._revision = self.renderer.prepare(self._requests(mode), match=True, **self._comparison_options(),**self._preview_options())
                self._match_revision = self._revision
            else:
                self._revision = self.renderer.prepare(self._requests(mode),**self._preview_options())
        except Exception as error:
            self.busy.hide()
            self._armed = None
            self._status("error", message=str(error))

    def _preview_options(self):
        return {}

    def _comparison_options(self):
        return {}

    def _ready(self, revision, previews):
        if self._closed or revision != self._revision:
            return
        self.busy.hide()
        mode, self._armed = self._armed, None
        if mode is None:
            self._status("ready", hits=sum(item.cache_hit for item in previews.values()), count=len(previews))
        elif mode != "compare":
            labels = ("a", "b") if mode == "ab" else (mode,)
            try:
                self.player.play([PlaybackItem(previews[label].listening_path, label) for label in labels])
            except (OSError, ValueError, RuntimeError) as error:
                self._status("error", message=str(error))

    def _matched(self, revision, result):
        if not self._closed and revision == self._revision == self._match_revision:
            self._match_result = result
            self._match_revision = None
            self._show_match()
            self._status("compared")

    def _failed(self, revision, message):
        if not self._closed and revision == self._revision:
            self.busy.hide()
            self._armed = None
            self._match_revision = None
            self._status("error", message=message)

    def _player_state(self, state, label):
        if self._closed:
            return
        if self.busy.isVisible() and state == "stopped":
            return
        if state in ("playing", "loading", "gap"):
            self._status(state, label=label)
        elif state in ("stopping", "stopped"):
            self._status(state)

    def stop(self):
        self._debounce.stop()
        self._armed = None
        self._revision = None
        self._match_revision = None
        self.renderer.cancel()
        self.busy.hide()
        self.player.stop()
        self._status("stopped")

    def changeEvent(self, event):
        super().changeEvent(event)
        if event.type() == QEvent.Type.WindowDeactivate and not self._closed:
            QTimer.singleShot(0, self._check_focus)

    def _check_focus(self):
        popup = QApplication.activePopupWidget()
        if not self._closed and not self.isActiveWindow() and not (popup and self.isAncestorOf(popup)):
            self.stop()
            self._status("focus")

    def closeEvent(self, event):
        self._closed = True
        self._debounce.stop()
        self._armed = None
        self._revision = None
        self.player.close()
        self.renderer.close()
        event.accept()
