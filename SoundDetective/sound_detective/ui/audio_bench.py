class AudioBench(QMainWindow):
    def __init__(self, *, player=None, renderer=None):
        super().__init__()
        self.player = player if player is not None else AudioPlayer(self)
        self.renderer = renderer if renderer is not None else PreviewRenderer(self)
        self._language = "en"
        self._revision = None
        self._armed = None
        self._match_result = None
        self._match_revision = None
        self._closed = False
        self._status_key, self._status_args = "idle", {}
        self.resize(1088, 612)
        self.setMinimumSize(960, 600)
        self._build()
        self._debounce = QTimer(self)
        self._debounce.setSingleShot(True)
        self._debounce.setInterval(220)
        self._debounce.timeout.connect(lambda: self._prepare(None))
        self.renderer.ready.connect(self._ready)
        self.renderer.failed.connect(self._failed)
        self.renderer.matched.connect(self._matched)
        self.player.state_changed.connect(self._player_state)
        self.player.error.connect(lambda message: self._status("error", message=message))
        self.player.device_changed.connect(lambda _: self._device())
        self.player.set_volume(self.volume.value() / 100)
        self._translate()

